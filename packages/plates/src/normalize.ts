/**
 * Нормализация номера (10_ §4, 16_ A10): верхний регистр, кириллица → латиница, без пробелов,
 * тире и точек. Нормализованный номер хранится в `plate_norm` и служит ключом поиска.
 */

/**
 * Буквы, которые есть и в кириллице, и в латинице (один рисунок на номере). Кириллические
 * переводятся в латинские — так же делает PASS24, поэтому импорт совпадает по ключу.
 * `І` (украинская/белорусская И) → `I`: встречается на номерах Беларуси.
 */
const CYRILLIC_TO_LATIN: Readonly<Record<string, string>> = {
  А: 'A',
  В: 'B',
  Е: 'E',
  К: 'K',
  М: 'M',
  Н: 'H',
  О: 'O',
  Р: 'P',
  С: 'C',
  Т: 'T',
  У: 'Y',
  Х: 'X',
  І: 'I',
};

/** Всё, что не буква и не цифра: пробелы (включая неразрывный), тире любого вида, точки, кавычки. */
const SEPARATORS = /[^\p{L}\p{N}]+/gu;

/** Нормализованная запись: только `A–Z`, `0–9` и буквы, которых в латинице нет (например «Ж»). */
export function normalizePlateText(raw: string): string {
  let out = '';
  for (const char of raw.toUpperCase().replace(SEPARATORS, '')) {
    out += CYRILLIC_TO_LATIN[char] ?? char;
  }
  return out;
}

/** Цифры из введённого номера — для поиска на посту «по цифрам» (в любом регистре и раскладке). */
export function plateDigits(raw: string): string {
  return raw.replace(/\D/g, '');
}
